# app/engine/config.py
# ============================================================
# УНИВЕРСАЛЬНЫЙ ДВИЖОК CRUD-ТАБЛИЦ — конфигурация.
#
# Идея: вместо того чтобы на каждую справочную таблицу (материалы,
# бренды, категории и т.д.) писать отдельный роутер + отдельный
# Alpine-шаблон вручную, мы один раз описываем таблицу декларативно
# через TableConfig — а движок (engine/api.py + engine/page.py) сам
# генерирует JSON API и HTML-страницу со списком+модалкой.
#
# Что покрывает движок:
#  - обычные поля (текст, число)
#  - computed_pairs — пара полей, взаимно пересчитываемых по формуле
#    (пример: price_excl_vat <-> price_incl_vat через vat_rate)
#  - relations — внешний ключ, отображаемый как выпадающий список
#    и как "живая ссылка" (имя связанной записи, а не голый ID)
#
# Чего движок НЕ покрывает (и не должен) — это осознанно:
#  - каскадные пересчёты между разными документами (продукт → спека
#    → заказ) — слишком специфичная бизнес-логика
#  - составные документы (заказ, инвойс) со своими правилами
#  - снапшоты (расчётные факты, которые не должны быть "живыми
#    ссылками") — для таких сценариев пишем отдельный код, движок
#    только для простых источников истины (справочников)
# ============================================================

from dataclasses import dataclass, field
from typing import Any, Literal, Optional
from sqlmodel import SQLModel


FieldWidget = Literal["text", "number", "select", "date", "time", "textarea", "radio"]


@dataclass
class FieldConfig:
    """Одно поле формы/списка."""
    name: str                      # имя атрибута в модели, например "short_name"
    label: str                     # подпись на русском для формы/списка
    widget: FieldWidget = "text"
    options: list[tuple[str, str]] = field(default_factory=list)
                                    # Статичный список опций (value, label) для
                                    # widget="select"/"radio" БЕЗ связи с другой
                                    # таблицей (в отличие от Relation — тот всегда
                                    # ссылается на реальную справочную таблицу с
                                    # id/name). Пример: Calculation.status —
                                    # фиксированный набор ["draft","active",...],
                                    # не таблица в БД. Для widget="radio" label
                                    # каждой опции — ЗАГЛУШКА на случай, если
                                    # динамическая подпись не подтянется (см.
                                    # radio_labels_field ниже) — например
                                    # Calculation.brand_slot использует
                                    # ("1","Вариант 1") как fallback, пока не
                                    # подтянуто название бренда из заявки. Пусто —
                                    # поле либо не select/radio, либо select
                                    # управляется через Relation как раньше.
    radio_labels_field: Optional[str] = None
                                    # Только для widget="radio": имя ключа в
                                    # editing (на фронте), где лежит СЛОВАРЬ
                                    # {value: label} с динамическими подписями.
                                    # Если подписи для конкретного value нет в
                                    # этом словаре (или radio_labels_field вообще
                                    # не задан) — используется статичный label
                                    # из options. None — radio-поле показывает
                                    # только статичные options-подписи.
    radio_labels_action: Optional[str] = None
                                    # Имя action (ключ в TableConfig.
                                    # action_handlers) — вызывается АВТОМАТИЧЕСКИ
                                    # при открытии формы существующей записи (см.
                                    # openEdit() в page.py), без клика человека,
                                    # результат подмешивается в editing тем же
                                    # способом, что и обычная ActionButton.
                                    # Используется вместе с radio_labels_field —
                                    # обработчик должен вернуть {radio_labels_
                                    # field: {value: label, ...}}. Пример:
                                    # Calculation.brand_slot ->
                                    # radio_labels_action="brand_slot_labels" —
                                    # подтягивает реальные названия брендов из
                                    # связанной заявки. None — подписи не
                                    # подгружаются автоматически, используется
                                    # только статичный fallback из options.
    required: bool = False
    placeholder: str = ""
    in_list: bool = True           # показывать в таблице списка
    list_width: Optional[str] = None   # например "26%" или "100px"
    searchable: bool = False       # участвует в текстовом поиске (q=...)
    search_toggle: bool = True     # если searchable=True и на таблице включены
                                    # enable_search_toggles — показывать ли для
                                    # этого поля отдельный чекбокс "искать по …"
                                    # (True) или включать его в поиск всегда,
                                    # без отдельного управления (False)
    search_default: bool = True    # если search_toggle=True — состояние чекбокса
                                    # при первой загрузке страницы (True — отмечен,
                                    # False — снят; человек может переключить вручную,
                                    # выбор держится, пока страница открыта)
    is_numeric: bool = False       # для выравнивания по правому краю и форматирования
    in_form: bool = True           # показывать в форме модалки (по умолчанию — да)
    form_width: Optional[str] = None   # фиксированная ширина поля в форме, например "140px";
                                        # если не задано — поле растягивается на всю доступную ширину ряда
    default: Any = None            # значение по умолчанию при создании новой записи
    default_from_constant: Optional[str] = None
                                    # Имя ключа в справочнике constant
                                    # (Constant.key) — если задано, значение
                                    # по умолчанию при создании новой записи
                                    # берётся ДИНАМИЧЕСКИ из this.constants
                                    # (см. openCreate() в page.py), а не из
                                    # статичного `default` выше — человек
                                    # может поменять его через /constant-v2
                                    # без изменения кода, и следующая новая
                                    # запись сразу подхватит новое значение.
                                    # ТРЕБУЕТ TableConfig.needs_constants=True
                                    # у этой таблицы, иначе this.constants
                                    # будет пуст и сработает fallback. Если
                                    # ключ не найден в this.constants (ещё не
                                    # загрузился, или удалили) — используется
                                    # статичный `default` как fallback, не
                                    # пустая строка. Пример: Calculation.
                                    # name_template -> "calculation_name_
                                    # template" (решение Вахтанга 2026-08-22:
                                    # дефолт шаблона названия редактируется
                                    # через constant, не хардкодом в коде).
    default_first_option: bool = False
                                    # Только для relation-полей (FK-select).
                                    # Если True — при создании НОВОЙ записи
                                    # (см. openCreate() в page.py) подставляет
                                    # id ПЕРВОЙ записи связанной таблицы (по
                                    # порядку, в котором relationOptions уже
                                    # загружены — обычно по id) как значение
                                    # по умолчанию, вместо null. Если список
                                    # опций ещё не загружен или пуст — просто
                                    # остаётся null, без ошибки. Пример:
                                    # Calculation.product_type_rate_id — новая
                                    # калькуляция сразу получает первую по id
                                    # запись справочника "Стоимость сборки"
                                    # (решение Вахтанга 2026-08-26: заводить
                                    # отдельную константу/поиск по имени —
                                    # избыточно, "первая запись = типовая"
                                    # достаточно просто и понятно).
                                    # (если None — используется 0 для числовых, '' для текстовых)
    readonly: bool = False         # поле показывается в форме как обычный текст,
                                    # не как input — редактировать нельзя ни через
                                    # форму, ни через API (см. update_item в api.py)
    virtual: bool = False          # поле НЕ хранится в модели/БД вообще — не
                                    # передаётся в create/update, не сериализуется
                                    # из instance. Значение подтягивается на фронте
                                    # отдельным запросом (см. source_constant_key)
                                    # и показывается как readonly "живая ссылка".
                                    # Пример: ставка НДС у материала — общая для
                                    # всех, хранится только в constants, но должна
                                    # быть видна в карточке.
    source_constant_key: Optional[str] = None  # для virtual-полей: ключ константы
                                    # в справочнике constants, откуда фронт берёт
                                    # значение для отображения в форме/списке.
    row_actions: list[str] = field(default_factory=list)
                                    # Заголовки кнопок, показанных СРАЗУ ЗА этим
                                    # полем в том же ряду формы (не под формой
                                    # целиком, в отличие от TableConfig.
                                    # extra_actions). Видны только у существующей
                                    # записи (editing.id). По умолчанию (когда
                                    # row_action_names не задан для этой позиции —
                                    # см. ниже) кнопка остаётся disabled-заглушкой,
                                    # как было изначально. Пример: у request каждое
                                    # поле brand_slot_N_id имеет по две кнопки —
                                    # «Спецификация» (реальный обработчик, см.
                                    # row_action_names) и «Пересчитать» (пока
                                    # заглушка — своей логики ещё нет).
    row_action_names: list[Optional[str]] = field(default_factory=list)
                                    # Параллельный row_actions список ИМЁН действий
                                    # (ключ в action_handlers, как и inline_action) —
                                    # None на позиции, где кнопка остаётся
                                    # disabled-заглушкой; строка — кнопка активна и
                                    # вызывает runAction(этим именем) по клику,
                                    # ровно как обычная ActionButton, просто
                                    # расположена рядом с конкретным полем, а не
                                    # отдельным блоком под вкладкой. Длина должна
                                    # совпадать с row_actions (используется по
                                    # индексу — zip), иначе позиция без пары
                                    # трактуется как заглушка. Введено 2026-08-27
                                    # вместе со спецификацией: у request
                                    # row_actions=["Спецификация","Пересчитать"],
                                    # row_action_names=["build_specification_1", None]
                                    # (номер слота зашит в имени action — см.
                                    # request_table в tables.py, по одному
                                    # обработчику на слот, т.к. в реестре
                                    # action_handlers ключи должны быть разными).
    list_as_dot: bool = False      # Только для select-полей со статичными
                                    # options (widget="select"/"radio"): в списке
                                    # показывать не текст значения, а цветную
                                    # точку (аналог is_deleted status-dot) с
                                    # подписью значения во всплывающей подсказке
                                    # (title), а не отдельной текстовой колонкой.
                                    # Цвет точки берётся по value через
                                    # dot_colors. Пример: Calculation.status —
                                    # компактнее текстовой колонки, особенно на
                                    # телефоне. False — поле рендерится в списке
                                    # как обычно (см. f.options -> optionLabel()).
    dot_colors: dict[str, str] = field(default_factory=dict)
                                    # Только вместе с list_as_dot=True: явное
                                    # сопоставление value -> CSS-цвет точки
                                    # (например {"draft": "#9c9c94", "active":
                                    # "#3f7d4f", ...}). Значение без записи в
                                    # словаре получает нейтральный цвет по
                                    # умолчанию (см. page.py).
    hint: str = ""                 # Короткая пояснительная строка, показанная
                                    # СРАЗУ ПОД полем в форме (серым, мельче
                                    # обычного текста) — например список доступных
                                    # плейсхолдеров под полем name_template, чтобы
                                    # не нужно было держать их в голове при вводе.
                                    # Пусто — подсказка не показывается.
    inline_action: Optional[str] = None
                                    # Имя действия (совпадает с
                                    # ActionButton.action из TableConfig.
                                    # action_buttons) — если задано, кнопка с
                                    # РЕАЛЬНЫМ обработчиком (не disabled-заглушка,
                                    # в отличие от row_actions) рендерится СРАЗУ
                                    # за этим полем в том же ряду формы, компактно,
                                    # справа. Кнопка вызывает тот же runAction(),
                                    # что и обычная ActionButton на вкладке — этим
                                    # полем управляется только ЕЁ РАСПОЛОЖЕНИЕ
                                    # (рядом с конкретным полем вместо отдельного
                                    # блока под вкладкой целиком). Пример:
                                    # Calculation.full_name -> inline_action=
                                    # "recalc_full_name" — кнопка «Пересчитать
                                    # название» стоит в одном ряду с полем
                                    # «Полное название». Если задано — эта
                                    # ActionButton НЕ дублируется отдельным блоком
                                    # под вкладкой (см. render_action_buttons).
    on_change_action: Optional[str] = None
                                    # Имя КЛИЕНТСКОГО действия (ключ в
                                    # CLIENT_ACTIONS, см. page.py — НЕ имя
                                    # серверного action_handlers) — вызывается
                                    # АВТОМАТИЧЕСКИ при каждом изменении ЭТОГО
                                    # поля в открытой форме (не только при
                                    # открытии, в отличие от radio_labels_action
                                    # у ДРУГОГО поля). Только для relation-полей
                                    # (select со связью на другую таблицу) — см.
                                    # рендер @change в render_form_rows. Пример:
                                    # Calculation.request_id ->
                                    # on_change_action="brand_slot_labels" —
                                    # при выборе/смене заявки в форме сразу, без
                                    # похода на сервер и без сохранения,
                                    # подписи радиокнопок brand_slot обновляются
                                    # реальными названиями брендов ЭТОЙ заявки
                                    # (решение Вахтанга 2026-08-22: в 99% случаев
                                    # калькуляция создаётся на основании заявки,
                                    # значит бренды должны быть видны сразу как
                                    # заявка выбрана, а не только после
                                    # сохранения). None — обычное поведение,
                                    # никакого побочного эффекта при смене поля.
    tab: Optional[str] = None      # Если у TableConfig задан form_tabs — на какой
                                    # вкладке формы показывается это поле (должно
                                    # совпадать с одним из значений form_tabs). None
                                    # (или form_tabs не задан у таблицы вообще) —
                                    # поле рендерится как раньше, без вкладок.
                                    # Поля без tab при заданном form_tabs попадают
                                    # на первую вкладку по умолчанию (см.
                                    # _build_form_layout в page.py).


@dataclass
class ComputedPair:
    """
    Пара полей, взаимно пересчитываемых друг из друга по формуле.
    Пример: цена без НДС <-> цена с НДС, через ставку НДС.

    formula="vat" — единственный встроенный тип пока. Формула:
        field_b = field_a * (1 + rate / 100)
        field_a = field_b / (1 + rate / 100)
    Новые формулы (наценка, скидка) добавляются в engine/formulas.py
    по мере реальной потребности — не заранее.

    Источник ставки — ровно один из двух:
      - rate_field: имя поля модели (ставка хранится в самой записи,
        как раньше у Material.vat_rate)
      - rate_constant_key: ключ в справочнике constants (ставка —
        общая "живая ссылка", не хранится в записи вообще; пример —
        vat_rate после отказа от per-material поля). Значение
        подгружается на бэкенде из таблицы constant при пересчёте,
        и на фронте — при открытии формы, показывается как readonly.
    Если задан rate_constant_key — rate_field не используется как
    источник данных, но по-прежнему нужен как имя, под которым
    ставка живёт в editing на фронте (чтобы JS-пересчёт работал
    единообразно что для поля модели, что для константы).
    """
    field_a: str
    field_b: str
    rate_field: str
    rate_constant_key: Optional[str] = None
    formula: Literal["vat"] = "vat"
    label_a: str = ""
    label_b: str = ""
    label_rate: str = ""


@dataclass
class Relation:
    """
    Связь с другой справочной таблицей — внешний ключ, показываемый
    как выпадающий список в форме и как имя (не ID) в списке.
    "Живая ссылка" в терминах проекта: показывается текущее имя
    связанной записи, обновляется само при переименовании.
    """
    field: str                     # например "brand_id"
    target_table: str              # ключ таблицы в TABLE_REGISTRY, например "brand"
    display_field: str = "name"    # какое поле связанной записи показывать
    label: str = ""
    show_filter_chips: bool = True
                                    # Показывать ли ряд чипов-фильтров
                                    # ("Все" + одна кнопка на каждое значение
                                    # связанной таблицы) в верхней панели
                                    # списка. По умолчанию True (как было
                                    # у material/brand — один relation, один
                                    # осмысленный ряд фильтров). У документов
                                    # с несколькими relation-полями сразу
                                    # (request — 5 штук: 2 клиента + 3 бренда)
                                    # ряд чипов на КАЖДОЕ поле выглядит
                                    # захламлённо и малополезно — там лучше
                                    # обычный текстовый поиск (см. request_table,
                                    # enable_search_toggles). False отключает
                                    # чипы именно для этого relation-поля, не
                                    # трогая остальные поля/таблицы.
    searchable_fields: list[str] = field(default_factory=list)
                                    # Текстовые поля СВЯЗАННОЙ (target_table)
                                    # таблицы, по которым можно искать через
                                    # этот relation (например для request.
                                    # client_id -> ["short_name", "full_name"]
                                    # клиента). Пусто — по этому relation
                                    # текстовый поиск не ведётся (обычная
                                    # ситуация для большинства relation-полей,
                                    # где ищут через сам список/чипы, а не
                                    # текстом). Заполнено — поле участвует в
                                    # общем текстовом поиске (q=...) как JOIN
                                    # по target_table, с тем же чекбоксом
                                    # "искать по …" (enable_search_toggles),
                                    # что и обычные текстовые FieldConfig —
                                    # см. searchable_relations()/toggleable_
                                    # search_relations() ниже и join-логику
                                    # в list_items (api.py).
    search_toggle: bool = True
    search_default: bool = True
    search_label: str = ""         # подпись чекбокса поиска (например
                                    # "Клиент (заказчик)"); если пусто —
                                    # используется label этого Relation.


@dataclass
class FormRow:
    """
    Один визуальный ряд формы — список имён полей, которые должны
    отображаться рядом друг с другом (а не каждое на отдельной строке).

    Если в ряду 2+ поля — рендерится как flex-контейнер (.field-row
    для обычных полей или .price-pair, если хотя бы одно поле ряда
    входит в computed_pairs). Поля, не перечисленные ни в одном
    FormRow, идут каждое отдельным рядом — по порядку объявления в
    TableConfig.fields.
    """
    field_names: list[str] = field(default_factory=list)


@dataclass
class ActionButton:
    """Кнопка в теле модалки формы (рядом с extra_actions-заглушками),
    но с РЕАЛЬНОЙ логикой — вызывает конкретный именованный action на
    бэкенде (или клиентскую JS-функцию, см. client_side ниже) вместо
    простого disabled-плейсхолдера. Пример: кнопка «Сформировать
    название» у calculation. Не путать с TableConfig.extra_actions
    (список заголовков disabled-заглушек без реального обработчика) —
    этот механизм для случаев, когда логика уже реализована, но кнопка
    не является обычным save/delete."""
    action: str                    # ключ действия — используется и как
                                    # имя серверного обработчика
                                    # (action_handlers), и как имя
                                    # клиентской JS-функции (см.
                                    # client_side ниже), и в URL при
                                    # серверном варианте
    label: str                     # подпись кнопки
