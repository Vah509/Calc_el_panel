                                    #     внешних ссылок на них: DELETE удаляет
                                    #     строку физически, но только если у неё нет
                                    #     дочерних записей (см. hierarchy.child_key) —
                                    #     иначе 422 с понятным сообщением. Синхронная
                                    #     проверка count(), без processor.
