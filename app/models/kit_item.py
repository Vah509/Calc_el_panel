# ============================================================
# KitItem — одна позиция состава комплекта: ссылка на материал +
# количество. Пример: комплект "Подключение ВА47 3P 63А" состоит
# из нескольких KitItem (кабель N м, наконечник N шт, ...).
#
# ВРЕМЕННО (v39) заведена как ОБЫЧНАЯ ПЛОСКАЯ ТАБЛИЦА старого
# движка — см. подробное обоснование в app/models/kit.py (тот же
# осознанный временный шаг: вручную занести пробные строки состава
# до того, как будет спроектирован полноценный подбор материалов
# внутри карточки kit).
#
# Принципиальное отличие от kit_group/kit_section/kit: у KitItem
# НЕТ soft-delete (is_deleted). Согласно принципу "живая ссылка vs
# снапшот" (см. HANDOFF_kits_and_calculation.md) — калькуляция
# хранит ссылку только на kit_id и разворачивает состав live при
# пересчёте, то есть НИЧТО не ссылается на конкретный KitItem
# напрямую. Значит удаление позиции состава — всегда безусловное
# физическое удаление сразу (delete_mode="hard" в движке, дефолт),
# без пометки и без purge-processor — это не "поставлено на паузу
# ради будущего шага", а осознанное окончательное решение по этой
# конкретной таблице.
#
# quantity — float, не int: материалы состава мерятся не только
# штуками (кабель, лента — метры; те же дробные количества, что
# обсуждались бы для калькуляции, здесь применимы уже сейчас).
# ============================================================

from typing import Optional
from sqlmodel import SQLModel, Field


class KitItem(SQLModel, table=True):
    id: Optional[int] = Field(default=None, primary_key=True)
    kit_id: Optional[int] = Field(default=None, foreign_key="kit.id")
    material_id: Optional[int] = Field(default=None, foreign_key="material.id")
    quantity: float = Field(default=1.0)
