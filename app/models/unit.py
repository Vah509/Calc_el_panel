# Единица измерения (шт/м/кг/услуга и т.п.) — плоский справочник,
# по образцу KitGroup: только "Название" (хранится сразу в сокращённом
# виде — "шт", "м", "кг", "услуга" — используется везде как есть:
# в списке/форме материала, в будущих спецификации/счёте) и "Порядок"
# для ручной сортировки в выпадающих списках.
#
# "Услуга" (например сборка щита) — это ОБЫЧНЫЙ материал с
# unit = "услуга", отдельной сущности для услуг не заводим (решение
# Вахтанга, 2026-08-23) — так проще, не плодит третий тип позиции
# в будущем calculation_item.
# ============================================================

from typing import Optional
from sqlmodel import SQLModel, Field


class Unit(SQLModel, table=True):
    id: Optional[int] = Field(default=None, primary_key=True)

    name: str = Field(unique=True)
    sort_order: int = Field(default=0)
