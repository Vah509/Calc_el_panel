# scripts/lib/read_archive.py
# ============================================================
# Читает список файлов внутри ZIP-архива ДО распаковки.
# Нужно для Telegram-отчёта "что вообще менялось" — даже если
# сборка упадёт и ничего не попадёт в реальный репозиторий, мы
# всё равно знаем, что было в архиве.
#
# В Python это проще, чем парсить вывод `unzip -l` регуляркой
# (как было в оригинальной Node-версии) — используем встроенный
# модуль zipfile напрямую.
# ============================================================

import zipfile


def read_archive_file_list(zip_path: str) -> list[str]:
    """
    Возвращает список путей файлов внутри архива (без папок).
    Бросает понятную ошибку, если архив повреждён/недоступен.
    """
    try:
        with zipfile.ZipFile(zip_path, "r") as zf:
            names = zf.namelist()
    except Exception as err:
        raise RuntimeError(f"Не удалось прочитать список файлов архива ({zip_path}): {err}") from err

    return [name for name in names if not name.endswith("/")]
